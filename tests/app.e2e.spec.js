test('operator image review shows badges, approves and requires rejection reason', async ({ page }) => {
  const profile = { id: 'test-user', nickname: '다중', server: '쥬엔', job: '바드', power: 92000, level: 7, intro: '검증용 프로필', availability: '', dungeons: ['멘트99'], public: true, verifiedAt: null };
  const rows = ['first', 'second'].map((id, i) => ({ request_id: id, user_id: id, nickname: i ? '검증용 모험가' : '다중', server: '쥬엔', power: 92000, level: 7, current_nickname: i ? '검증용 모험가' : '다중', current_server: '쥬엔', current_power: 90000, current_level: 6, status: 'pending', evidence: '', has_image: 1, profile_power: 90000, profile_level: 6, requested_at: '2026-10-23 09:00:00' }));
  await page.addInitScript(() => sessionStorage.setItem('asgard-session', 'test-session'));
  await page.route('**/api/**', async route => {
    const path = new URL(route.request().url()).pathname;
    if (path.endsWith('/image')) return route.fulfill({ contentType: 'image/png', path: 'public/assets/jobs/prophet.png' });
    let data;
    if (path === '/api/me') data = { user: { id: profile.id, username: 'developer', isAdmin: true }, profile };
    else if (path === '/api/profiles') data = [profile];
    else if (path === '/api/parties') data = [];
    else if (path === '/api/admin/verifications') data = rows;
    else if (path.endsWith('/review')) {
      const body = route.request().postDataJSON();
      const row = rows.find(r => r.request_id === body.requestId);
      row.status = body.decision === 'approve' ? 'approved' : 'rejected'; row.evidence = ''; row.has_image = 0; row.note = body.note;
      data = { ok: true };
    } else data = {};
    await route.fulfill({ json: data });
  });
  await page.goto('/');
  await page.getByRole('button', { name: '모험가 찾기', exact: true }).click();
  await expect(page.getByText('신스 7레벨', { exact: true })).toBeVisible();
  await expect(page.getByText('전투력 92,000', { exact: true })).toBeVisible();
  await expect(page.locator('.account-identity')).toHaveText('developer관리자');
  await page.getByRole('button', { name: '인증 검토', exact: true }).click();
  await expect(page.getByRole('img', { name: '다중 캐릭터 능력치 인증 제출 이미지' })).toBeVisible();
  const approve = page.getByRole('button', { name: '승인하고 인증 뱃지 부여' });
  await expect(approve).toBeDisabled();
  await page.screenshot({ path: '/tmp/asgard-review.png' });
  await page.getByRole('checkbox', { name: /이미지의 캐릭터명/ }).check();
  await approve.click();
  await expect(page.getByRole('heading', { name: '검증용 모험가', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '반려하기' })).toBeDisabled();
  await page.getByLabel('검토 의견 · 반려 시 필수').fill('캐릭터명 확인이 필요합니다.');
  await page.getByRole('button', { name: '반려하기' }).click();
  await expect(page.getByRole('heading', { name: '검토할 신청이 없습니다' })).toBeVisible();
  expect(rows.map(r => r.status)).toEqual(['approved', 'rejected']);
});
